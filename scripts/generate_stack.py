"""Write, or with --check verify, the stack locks and the matrix in docs/stack.md (#259).

Each stack in stack/stack.toml is resolved with ``uv pip compile`` from pyproject.toml's
mujoco and planning extras and the reference application's pins, and locked with every
artifact hash in stack/<name>.txt. The matrix in docs/stack.md is generated from those
locks and the declared requirements. With --check, nothing is written, and this fails if
a stack no longer resolves (contradictory constraints) or any file differs from what it
would write.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STACK = ROOT / "stack"
DOC = ROOT / "docs" / "stack.md"
START, END = "<!-- stack:start -->", "<!-- stack:end -->"
EXTRAS = ("mujoco", "planning")
# The matrix's rows, in order: what a user chooses or meets first.
ROWS = ("mujoco", "sscbirrt", "ssik", "sstsr", "ssmjviser", "numpy", "scipy")
PIN = re.compile(r"^([A-Za-z0-9_.-]+)==([^\s;\\]+)")


def _name(requirement: str) -> str:
    return re.split(r"[\[<>=!~;\s@]", requirement, maxsplit=1)[0].lower().replace("_", "-")


def lock(stack: dict[str, str], config: dict[str, object]) -> str:
    """The hash-locked requirements of ``stack``, from uv; exits if they do not resolve."""
    with tempfile.TemporaryDirectory() as tmp:
        applications = Path(tmp) / "applications.txt"
        applications.write_text("\n".join(config["applications"]) + "\n")  # type: ignore[arg-type]
        argv = [
            "uv", "pip", "compile", "pyproject.toml", str(applications),
            *(a for e in EXTRAS for a in ("--extra", e)),
            "--python-version", stack["python"],
            "--python-platform", str(config["platform"]),
            "--resolution", stack["resolution"],
            "--exclude-newer", str(config["exclude_newer"]),
            "--generate-hashes", "--no-header", "--no-annotate", "--quiet",
        ]  # fmt: skip
        result = subprocess.run(argv, cwd=ROOT, capture_output=True, text=True, check=False)
    if result.returncode != 0:
        raise SystemExit(f"stack {stack['name']!r} does not resolve:\n{result.stderr}")
    header = (
        f"# The {stack['name']} stack: Python {stack['python']}, {config['platform']},"
        f" resolution {stack['resolution']}, nothing after {config['exclude_newer']}.\n"
        "# Generated by scripts/generate_stack.py from pyproject.toml and stack/stack.toml.\n"
    )
    return header + result.stdout


def pins(text: str) -> dict[str, str]:
    return {_name(m[1]): m[2] for line in text.splitlines() if (m := PIN.match(line))}


def matrix(config: dict[str, object], locks: dict[str, str]) -> str:
    project = tomllib.loads((ROOT / "pyproject.toml").read_text())["project"]
    declared: dict[str, tuple[str, str]] = {}
    for extra in EXTRAS:
        for r in project["optional-dependencies"][extra]:
            kind, spec = declared.get(_name(r), ("", ""))
            declared[_name(r)] = (
                f"{kind}, `{extra}`" if kind else f"extra `{extra}`",
                f"{spec}, {r}" if spec else r,
            )
    for r in config["applications"]:  # type: ignore[attr-defined]
        declared[_name(r)] = ("reference application", r)
    stacks: list[dict[str, str]] = config["stacks"]  # type: ignore[assignment]
    head = " | ".join(f"{s['name']} (Python {s['python']})" for s in stacks)
    rows = [
        f"| Package | Kind | Declared | {head} |",
        "| --- | --- | --- |" + " --- |" * len(stacks),
    ]
    rows.append(
        "| Python | `requires-python` | "
        f"`{project['requires-python']}` | " + " | ".join(s["python"] for s in stacks) + " |"
    )
    for name in ROWS:
        kind, spec = declared.get(name, ("installed with the above", ""))
        cells = [pins(locks[s["name"]]).get(name, "-") for s in stacks]
        rows.append(
            f"| {name} | {kind} | {f'`{spec}`' if spec else '-'} | " + " | ".join(cells) + " |"
        )
    return "\n".join(rows)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if anything is out of date")
    args = parser.parse_args()
    config = tomllib.loads((STACK / "stack.toml").read_text())
    locks = {s["name"]: lock(s, config) for s in config["stacks"]}
    expected = {STACK / f"{name}.txt": text for name, text in locks.items()}
    text = DOC.read_text()
    block = re.compile(re.escape(START) + ".*?" + re.escape(END), re.S)
    if not block.search(text):
        raise SystemExit(f"{DOC} has no {START} ... {END} block")
    expected[DOC] = block.sub(lambda _: f"{START}\n{matrix(config, locks)}\n{END}", text)
    stale = [p for p, t in expected.items() if not p.is_file() or p.read_text() != t]
    if args.check:
        for path in stale:
            print(
                f"out of date: {path.relative_to(ROOT)}; run {Path(__file__).name}", file=sys.stderr
            )
        return 1 if stale else 0
    for path in stale:
        path.write_text(expected[path])
    return 0


if __name__ == "__main__":
    sys.exit(main())
